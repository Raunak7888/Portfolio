// redesign.sh:v1 : writes src/content/image-meta.generated.ts
// usage: node scripts/gen-image-meta.mjs --shots "/uploads/algoforge1.png,/uploads/algoforge2.png"
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const argShots = (() => {
    const i = process.argv.indexOf("--shots");
    return i > -1 && process.argv[i + 1] ? process.argv[i + 1].split(",").filter(Boolean) : [];
})();

function dims(buf) {
    if (buf.length > 24 && buf.subarray(1, 4).toString() === "PNG") return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
    if (buf[0] === 0xff && buf[1] === 0xd8) {
        let i = 2;
        while (i < buf.length - 9) {
            if (buf[i] !== 0xff) { i++; continue; }
            const m = buf[i + 1];
            if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
            i += 2 + buf.readUInt16BE(i + 2);
        }
    }
    if (buf.subarray(0, 4).toString() === "RIFF" && buf.subarray(8, 12).toString() === "WEBP") {
        const t = buf.subarray(12, 16).toString();
        if (t === "VP8X") return { w: 1 + buf.readUIntLE(24, 3), h: 1 + buf.readUIntLE(27, 3) };
        if (t === "VP8L") { const b = buf.readUInt32LE(21); return { w: 1 + (b & 0x3fff), h: 1 + ((b >> 14) & 0x3fff) }; }
        if (t === "VP8 ") return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
    }
    if (buf.subarray(0, 3).toString() === "GIF") return { w: buf.readUInt16LE(6), h: buf.readUInt16LE(8) };
    return null;
}

const sources = ["src/content/projects.ts", "src/Data/Project.json", "src/Data/Data.json"];
const urls = new Set(argShots);
for (const s of sources) {
    const p = path.join(root, s);
    if (!fs.existsSync(p)) continue;
    for (const m of fs.readFileSync(p, "utf8").matchAll(/\/uploads\/[A-Za-z0-9._-]+\.(?:webp|png|jpe?g|avif|gif)/gi)) urls.add(m[0]);
}

const meta = {};
const unknown = [];
for (const u of [...urls].sort()) {
    const file = path.join(root, "public", u);
    if (!fs.existsSync(file)) continue;
    try {
        const d = dims(fs.readFileSync(file));
        if (d && d.w > 0 && d.h > 0) meta[u] = d; else unknown.push(u);
    } catch { unknown.push(u); }
}

const out =
    `// redesign.sh:v1 : generated by scripts/gen-image-meta.mjs. Do not edit by hand.\n` +
    `// Intrinsic sizes let frames reserve space (no layout shift) and never crop a screenshot.\n` +
    `export const IMAGE_META: Record<string, { w: number; h: number }> = ${JSON.stringify(meta, null, 4)};\n\n` +
    `export const ALGOFORGE_SHOTS: string[] = ${JSON.stringify(argShots, null, 4)};\n`;
const target = path.join(root, "src/content/image-meta.generated.ts");
const tmp = target + ".tmp." + process.pid;
fs.writeFileSync(tmp, out);
fs.renameSync(tmp, target);
console.log(`image meta: ${Object.keys(meta).length} sized, ${unknown.length} without readable size, ${argShots.length} AlgoForge shots`);
if (unknown.length) console.log("no intrinsic size for (default ratio used): " + unknown.join(", "));
